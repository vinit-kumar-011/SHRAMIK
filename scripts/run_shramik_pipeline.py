"""Load a validated canonical CSV, compute analytics and persist one reproducible run.

Example (DEMO only):
  python -m scripts.run_shramik_pipeline --input-csv data/demo_observations.csv \
      --analysis-mode DEMO --demand-signal-type DEMO_JOB_DEMAND \
      --supply-signal-type DEMO_TRAINING_COMPLETIONS --random-seed 26246

Use a server-side DATABASE_URL. This command performs data writes; it does not change schema.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path
from uuid import uuid4

from sqlalchemy import create_engine, text
from sqlalchemy.exc import SQLAlchemyError

from ml.analytics_engine import AnalyticsConfig, AnalyticsInputError, compute_analytics
from ml.ingestion import IngestionValidationError, read_observations_csv
from ml.repository import (
    DatabaseValidationError,
    load_reference_catalog,
    persist_analytics,
    persist_observations,
    validate_against_database,
)


def _database_url() -> str:
    url = os.getenv("DATABASE_URL", "").strip()
    if not url:
        raise RuntimeError("DATABASE_URL is required. Do not place database credentials in the CSV or frontend.")
    if url.startswith("postgres://"):
        url = "postgresql+psycopg://" + url[len("postgres://"):]
    elif url.startswith("postgresql://"):
        url = "postgresql+psycopg://" + url[len("postgresql://"):]
    return url


def _arguments() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="SHRAMIK canonical ingestion and analytics pipeline.")
    parser.add_argument("--input-csv", required=True, help="Canonical observations CSV; schema is documented in docs/methodology/SHRAMIK_ANALYTICS_PIPELINE_V1.md.")
    parser.add_argument("--analysis-mode", required=True, choices=("OFFICIAL", "DEMO"))
    parser.add_argument("--demand-signal-type", required=True)
    parser.add_argument("--supply-signal-type", required=True)
    parser.add_argument("--demand-source-id", help="Optional source UUID to disambiguate demand records.")
    parser.add_argument("--supply-source-id", help="Optional source UUID to disambiguate supply records.")
    parser.add_argument("--min-history", type=int, default=3)
    parser.add_argument("--forecast-horizon", type=int, default=1)
    parser.add_argument("--gap-threshold", type=float, default=0.10)
    parser.add_argument("--min-forecast-demand", type=float, default=0.0)
    parser.add_argument("--emerging-growth-threshold", type=float, default=0.20)
    parser.add_argument("--random-seed", type=int, help="Seed when the synthetic dataset was generated by a seeded generator; omit for externally supplied/static data.")
    parser.add_argument("--generator-name", default="externally_supplied_demo_dataset")
    parser.add_argument("--generator-version", default="1.0")
    parser.add_argument("--output-json", help="Optional path for a copy of the output payload.")
    return parser.parse_args()


def main() -> int:
    args = _arguments()
    try:
        dataset = read_observations_csv(args.input_csv)
        if not any(r.kind == "DEMAND" and r.signal_type == args.demand_signal_type for r in dataset.observations):
            raise IngestionValidationError(f"No DEMAND rows have signal_type={args.demand_signal_type!r}.")
        if not any(r.kind == "SUPPLY" and r.signal_type == args.supply_signal_type for r in dataset.observations):
            raise IngestionValidationError(f"No SUPPLY rows have signal_type={args.supply_signal_type!r}.")

        config = AnalyticsConfig(
            min_history=args.min_history,
            forecast_horizon=args.forecast_horizon,
            gap_threshold=args.gap_threshold,
            min_forecast_demand=args.min_forecast_demand,
            emerging_growth_threshold=args.emerging_growth_threshold,
        )
        run_id = str(uuid4())
        engine = create_engine(_database_url(), pool_pre_ping=True)
        with engine.begin() as conn:
            conn.execute(text("SELECT pg_advisory_xact_lock(hashtext('shramik-canonical-pipeline-v1'))"))
            catalog = load_reference_catalog(conn)
            validate_against_database(
                dataset.observations, catalog, analysis_mode=args.analysis_mode
            )
            loaded_rows = persist_observations(
                conn,
                dataset.observations,
                input_sha256=dataset.sha256,
                random_seed=args.random_seed,
                generator_name=args.generator_name,
                generator_version=args.generator_version,
            )
            # The fact rows are inserted/upserted in this same transaction. The engine
            # computes only skill-specific district outputs; aggregates remain stored
            # as aggregates and are never fanned out into invented skill records.
            result = compute_analytics(
                loaded_rows,
                analysis_mode=args.analysis_mode,
                demand_signal_type=args.demand_signal_type,
                supply_signal_type=args.supply_signal_type,
                demand_source_id=args.demand_source_id,
                supply_source_id=args.supply_source_id,
                config=config,
                calculation_run_id=run_id,
            )
            # The canonical skill table is authoritative for sector identity when a
            # valid DISTRICT_SKILL input omits sector_id. Raw observations stay unchanged.
            for forecast in result["forecast_results"]:
                skill = catalog["skills"].get(forecast["skill_id"])
                if not skill:
                    raise DatabaseValidationError(
                        f"Forecast references unknown skill_id {forecast['skill_id']!r}."
                    )
                canonical_sector_id = skill["sector_id"]
                if forecast["sector_id"] and forecast["sector_id"] != canonical_sector_id:
                    raise DatabaseValidationError("Forecast sector conflicts with canonical skill mapping.")
                forecast["sector_id"] = canonical_sector_id
            counts = persist_analytics(conn, result)

        engine.dispose()
        payload = {
            "run": {
                "calculation_run_id": result["calculation_run_id"],
                "input_sha256": dataset.sha256,
                "input_rows": dataset.row_count,
                "analysis_mode": args.analysis_mode,
                "demand_signal_type": args.demand_signal_type,
                "supply_signal_type": args.supply_signal_type,
                "config": {
                    "min_history": config.min_history,
                    "forecast_horizon": config.forecast_horizon,
                    "gap_threshold": config.gap_threshold,
                    "min_forecast_demand": config.min_forecast_demand,
                    "emerging_growth_threshold": config.emerging_growth_threshold,
                },
                "persisted": counts,
            },
            "result": result,
        }
        rendered = json.dumps(payload, indent=2, sort_keys=True)
        if args.output_json:
            output_path = Path(args.output_json)
            output_path.parent.mkdir(parents=True, exist_ok=True)
            output_path.write_text(rendered + "\n", encoding="utf-8")
        print(rendered)
        return 0
    except (IngestionValidationError, DatabaseValidationError, AnalyticsInputError, ValueError, RuntimeError) as exc:
        print(f"SHRAMIK pipeline rejected the run: {exc}", file=sys.stderr)
        return 2
    except SQLAlchemyError as exc:
        # Deliberately do not print SQL or connection details that may include secrets.
        print(
            "SHRAMIK pipeline failed because the database operation did not complete. "
            "The transaction was rolled back; check server-side logs and database connectivity.",
            file=sys.stderr,
        )
        return 3


if __name__ == "__main__":
    raise SystemExit(main())
