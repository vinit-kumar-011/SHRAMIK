"""Create deterministic, explicitly synthetic SHRAMIK demo history.

This generator never creates SOURCE_BACKED rows and never activates provisional skill mappings.
Run from the backend directory with:
  python -m app.ingestion.demo
"""

from __future__ import annotations

import argparse
import json
import os
import random
import uuid
from datetime import datetime, timezone
from typing import Any

from sqlalchemy import text
from urllib.parse import urlsplit

from app.core.config import get_settings
from app.ingestion.db import get_engine

GENERATOR_NAME = "shramik_demo_pilot"
GENERATOR_VERSION = "1.1.0"
DEMO_SOURCE_RELEASE = f"SYNTHETIC_DEMO_v{GENERATOR_VERSION}"
RANDOM_SEED = 20261022
YEARS = tuple(range(2021, 2026))
SKILL_IDS = (
    "nco2015_7112_0200",
    "nco2015_2512_0100",
    "nco2015_7411_0100",
)
DEMAND_SIGNAL = "DEMO_LABOUR_DEMAND"
SUPPLY_SIGNAL = "DEMO_AVAILABLE_WORKFORCE"
DEMO_NOTE = (
    "SYNTHETIC DEMO ONLY: generated by shramik_demo_pilot v1.1.0. "
    "Not a government statistic, observed labour-market measure, or official forecast."
)


PILOT_DISTRICT_ALIASES = (
    ("cuttack", "kataka"),
    ("ganjam",),
    ("khordha", "khurda"),
)


def _resolve_pilot_districts(rows: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Resolve the fixed demo pilot without inventing district IDs.

    The loaded national reference roster uses the display spelling "Kataka" for
    the canonical district row (LGD-backed ID IN-LGD-350) in this database.
    Accept "Cuttack" as its common display alias, while preserving the stored ID
    and display name in the generation metadata.
    """
    by_normalized_name = {row["name"].strip().lower(): dict(row) for row in rows}
    chosen = []
    for aliases in PILOT_DISTRICT_ALIASES:
        match = next(
            (by_normalized_name[name] for name in aliases if name in by_normalized_name),
            None,
        )
        if match:
            chosen.append(match)
    if len(chosen) != len(PILOT_DISTRICT_ALIASES):
        missing = [
            "/".join(aliases)
            for aliases in PILOT_DISTRICT_ALIASES
            if not any(name in by_normalized_name for name in aliases)
        ]
        raise RuntimeError(
            "Could not resolve the demo pilot districts against the canonical district roster. "
            f"Missing aliases: {missing}"
        )
    return chosen


def _district_selection(conn) -> tuple[str, list[dict[str, Any]]]:
    state = conn.execute(
        text("SELECT id FROM public.states WHERE code = 'OD' LIMIT 1")
    ).scalar()
    if not state:
        raise RuntimeError("Odisha state reference (code OD) was not found.")

    rows = conn.execute(
        text("""
            SELECT id, name FROM public.districts
            WHERE state_id = :state_id
            ORDER BY lower(name)
        """),
        {"state_id": state},
    ).mappings().all()
    return str(state), _resolve_pilot_districts([dict(row) for row in rows])


def _ensure_generation_run(conn, parameters: dict[str, Any]) -> str:
    existing = conn.execute(
        text("""
            SELECT id, parameters
            FROM public.synthetic_generation_runs
            WHERE generator_name = :name AND generator_version = :version
              AND random_seed = :seed
            ORDER BY generated_at DESC
            LIMIT 1
        """),
        {"name": GENERATOR_NAME, "version": GENERATOR_VERSION, "seed": RANDOM_SEED},
    ).mappings().first()
    if existing:
        stored = existing["parameters"]
        if isinstance(stored, str):
            stored = json.loads(stored)
        if stored != parameters:
            raise RuntimeError(
                "An existing generation run uses this generator/version/seed with different parameters. "
                "Bump GENERATOR_VERSION before changing this generator."
            )
        return str(existing["id"])

    return str(conn.execute(
        text("""
            INSERT INTO public.synthetic_generation_runs
                (generator_name, generator_version, random_seed, parameters, source_context)
            VALUES (:name, :version, :seed, CAST(:parameters AS jsonb), :context)
            RETURNING id
        """),
        {
            "name": GENERATOR_NAME,
            "version": GENERATOR_VERSION,
            "seed": RANDOM_SEED,
            "parameters": json.dumps(parameters, sort_keys=True),
            "context": (
                "Hackathon UI/integration smoke-test data only. Never use as official history, "
                "policy evidence, or a proxy for government figures."
            ),
        },
    ).scalar_one())


def _existing_value(conn, table: str, signal_column: str, signal: str,
                    generation_run_id: str, district_id: str, skill_id: str,
                    year: int, value_column: str):
    # Table/column names are selected only from constants in this module.
    return conn.execute(text(f"""
        SELECT {value_column} FROM public.{table}
        WHERE generation_run_id = :run_id
          AND district_id = :district_id AND skill_id = :skill_id
          AND observation_grain = 'DISTRICT_SKILL' AND period_type = 'YEAR'
          AND period_year = :year AND {signal_column} = :signal
          AND provenance_state = 'SYNTHETIC_DEMO' AND is_synthetic = TRUE
        LIMIT 1
    """), {"run_id": generation_run_id, "district_id": district_id,
           "skill_id": skill_id, "year": year, "signal": signal}).scalar()


LOCAL_DATABASE_HOSTS = {"localhost", "127.0.0.1", "::1"}
ALLOW_REMOTE_SYNTHETIC_ENV = "SHRAMIK_ALLOW_SYNTHETIC_REMOTE_DB"


def validate_demo_database_target(
    database_url: str | None,
    *,
    allow_remote_flag: bool = False,
    allow_remote_env: bool = False,
) -> None:
    """Refuse synthetic writes to an unknown/remote DB unless doubly opted in.

    A developer can use a local throwaway Postgres instance by default. Writing
    synthetic rows to a remote database requires both an explicit CLI flag and an
    explicit environment variable, so a routine CLI invocation cannot repopulate
    the shared Supabase project used by the official SIH showcase.
    """
    if not database_url or not database_url.strip():
        raise RuntimeError("DATABASE_URL is not configured; no demo rows were written.")

    try:
        parsed = urlsplit(database_url.strip())
        hostname = (parsed.hostname or "").lower()
    except ValueError as exc:
        raise RuntimeError("DATABASE_URL could not be parsed; refusing to write synthetic data.") from exc

    if hostname in LOCAL_DATABASE_HOSTS:
        return

    if allow_remote_flag and allow_remote_env:
        return

    raise RuntimeError(
        "Refusing to write SYNTHETIC_DEMO rows to a remote database. The official SIH "
        "showcase must use source-backed records only. For a local pilot, point DATABASE_URL "
        "to localhost. Remote synthetic writes require both --allow-synthetic-remote-db and "
        f"{ALLOW_REMOTE_SYNTHETIC_ENV}=true; do not enable this for the shared/showcase database."
    )


def seed_demo(*, allow_remote_db: bool = False) -> dict[str, Any]:
    settings = get_settings()
    allow_remote_env = os.getenv(ALLOW_REMOTE_SYNTHETIC_ENV, "").strip().lower() == "true"
    validate_demo_database_target(
        settings.database_url,
        allow_remote_flag=allow_remote_db,
        allow_remote_env=allow_remote_env,
    )
    engine = get_engine()
    inserted_demand = inserted_supply = unchanged = 0
    try:
        with engine.begin() as conn:
            state_id, districts = _district_selection(conn)
            skills_rows = conn.execute(
                text("""
                    SELECT id, name, is_active
                    FROM public.skills
                    WHERE id IN (:skill_1, :skill_2, :skill_3)
                    ORDER BY id
                """),
                {
                    "skill_1": SKILL_IDS[0],
                    "skill_2": SKILL_IDS[1],
                    "skill_3": SKILL_IDS[2],
                },
            ).mappings().all()
            skills_by_id = {row["id"]: dict(row) for row in skills_rows}
            missing = sorted(set(SKILL_IDS) - set(skills_by_id))
            if missing:
                raise RuntimeError(f"Demo pilot skill reference IDs were not found: {missing}")

            parameters = {
                "districts": [{"id": d["id"], "name": d["name"]} for d in districts],
                "skills": [{"id": skills_by_id[s]["id"], "name": skills_by_id[s]["name"]}
                           for s in SKILL_IDS],
                "years": list(YEARS),
                "observation_grain": "DISTRICT_SKILL",
                "quantity_unit": "persons",
                "quantity_semantics": "STOCK",
                "demand_signal_type": DEMAND_SIGNAL,
                "supply_signal_type": SUPPLY_SIGNAL,
                "generator_formula": "accelerating-demand-vs-conservative-supply-plus-seeded-small-jitter-v2",
            }
            run_id = _ensure_generation_run(conn, parameters)

            for district_index, district in enumerate(districts):
                for skill_index, skill_id in enumerate(SKILL_IDS):
                    rng = random.Random(RANDOM_SEED + district_index * 100 + skill_index * 10)
                    demand_base = 280 + district_index * 70 + skill_index * 120
                    supply_base = 260 + district_index * 60 + skill_index * 85

                    for year_index, year in enumerate(YEARS):
                        demand_value = max(
                            0,
                            round(demand_base * (1 + 0.025 * year_index + 0.012 * year_index * year_index) + rng.randint(-10, 10)),
                        )
                        supply_value = max(
                            0,
                            round(supply_base * (1 + 0.025 * year_index) + rng.randint(-10, 10)),
                        )

                        previous = _existing_value(
                            conn, "demand_observations", "demand_signal_type", DEMAND_SIGNAL,
                            run_id, district["id"], skill_id, year, "demand_quantity",
                        )
                        if previous is None:
                            conn.execute(text("""
                                INSERT INTO public.demand_observations
                                    (state_id, district_id, sector_id, skill_id, observation_grain,
                                     period_type, period_year, demand_quantity, quantity_unit,
                                     quantity_semantics, demand_signal_type, source_id, source_release,
                                     provenance_state, is_synthetic, generation_run_id, transformation_note)
                                VALUES
                                    (:state_id, :district_id, NULL, :skill_id, 'DISTRICT_SKILL',
                                     'YEAR', :year, :value, 'persons', 'STOCK', :signal, NULL,
                                     :source_release, 'SYNTHETIC_DEMO', TRUE, :run_id, :note)
                            """), {
                                "state_id": state_id, "district_id": district["id"],
                                "skill_id": skill_id, "year": year, "value": demand_value,
                                "signal": DEMAND_SIGNAL, "source_release": DEMO_SOURCE_RELEASE, "run_id": run_id, "note": DEMO_NOTE,
                            })
                            inserted_demand += 1
                        elif float(previous) == float(demand_value):
                            unchanged += 1
                        else:
                            raise RuntimeError(
                                f"Existing demo demand differs for {district['name']}, "
                                f"{skill_id}, {year}. Bump GENERATOR_VERSION to regenerate."
                            )

                        previous_supply = _existing_value(
                            conn, "supply_observations", "supply_signal_type", SUPPLY_SIGNAL,
                            run_id, district["id"], skill_id, year, "supply_quantity",
                        )
                        if previous_supply is None:
                            conn.execute(text("""
                                INSERT INTO public.supply_observations
                                    (state_id, district_id, sector_id, skill_id, observation_grain,
                                     period_type, period_year, supply_quantity, training_capacity,
                                     enrollment, completions, quantity_unit, quantity_semantics,
                                     supply_signal_type, source_id, source_release, provenance_state,
                                     is_synthetic, generation_run_id, transformation_note)
                                VALUES
                                    (:state_id, :district_id, NULL, :skill_id, 'DISTRICT_SKILL',
                                     'YEAR', :year, :value, NULL, NULL, NULL, 'persons', 'STOCK',
                                     :signal, NULL, :source_release, 'SYNTHETIC_DEMO', TRUE,
                                     :run_id, :note)
                            """), {
                                "state_id": state_id, "district_id": district["id"],
                                "skill_id": skill_id, "year": year, "value": supply_value,
                                "signal": SUPPLY_SIGNAL, "source_release": DEMO_SOURCE_RELEASE, "run_id": run_id, "note": DEMO_NOTE,
                            })
                            inserted_supply += 1
                        elif float(previous_supply) == float(supply_value):
                            unchanged += 1
                        else:
                            raise RuntimeError(
                                f"Existing demo supply differs for {district['name']}, "
                                f"{skill_id}, {year}. Bump GENERATOR_VERSION to regenerate."
                            )

            return {
                "generation_run_id": run_id,
                "generator": f"{GENERATOR_NAME} {GENERATOR_VERSION}",
                "random_seed": RANDOM_SEED,
                "analysis_mode": "DEMO",
                "provenance_state": "SYNTHETIC_DEMO",
                "districts": [d["name"] for d in districts],
                "skills": [{"id": skills_by_id[s]["id"], "name": skills_by_id[s]["name"],
                            "active_mapping": skills_by_id[s]["is_active"]} for s in SKILL_IDS],
                "years": list(YEARS),
                "demand_rows_inserted": inserted_demand,
                "supply_rows_inserted": inserted_supply,
                "existing_rows_unchanged": unchanged,
                "note": "These records are synthetic demo data and must never be reported as official evidence.",
            }
    finally:
        engine.dispose()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--allow-synthetic-remote-db",
        action="store_true",
        help=(
            "Explicit override for a remote database; also requires "
            f"{ALLOW_REMOTE_SYNTHETIC_ENV}=true. Never use on the SIH showcase database."
        ),
    )
    args = parser.parse_args()
    print(json.dumps(seed_demo(allow_remote_db=args.allow_synthetic_remote_db), indent=2, default=str))


if __name__ == "__main__":
    main()
